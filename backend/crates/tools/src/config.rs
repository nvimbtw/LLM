//! What the tools need from the machine they run on.

use std::time::Duration;

/// How many search results reach the model. Its context window is small and a
/// result it never reads is prompt it cannot spend on the answer.
const DEFAULT_RESULTS: usize = 3;

/// How many characters the whole rendered result may run to.
///
/// Sized against the engine's default `ctx_window` of 256 tokens, half of which
/// `orchestrate/chat.py` reserves for the reply — so the prompt has ~128 tokens
/// for the system block, the history *and* this. At roughly three characters a
/// token that is ~380 characters for everything, and a tool result is only ever
/// part of it.
///
/// Raise it with the window. A model at 1024 can afford four or five times this
/// and will answer better for it; a result that overruns is not an error, it
/// just evicts the conversation it was fetched for.
const DEFAULT_BUDGET_CHARS: usize = 320;

/// How long a tool may take before the turn gives up on it. The reply it feeds
/// is already generated by the time this is awaited, so the whole budget is
/// latency the person is watching.
const DEFAULT_TIMEOUT_SECS: u64 = 10;

#[derive(Clone, Debug)]
pub struct Config {
    /// A self-hosted SearXNG instance, e.g. `http://localhost:8888`.
    ///
    /// Takes precedence over `search_api_key` when both are set: naming an
    /// instance is a deliberate act, where a key can easily be left over in an
    /// environment from something else.
    pub search_url: Option<String>,
    /// Brave Search. Used only when no instance is named.
    pub search_api_key: Option<String>,
    pub search_results: usize,
    /// A ceiling on the whole rendered result, not on one line of it.
    pub search_budget_chars: usize,
    pub timeout: Duration,
}

impl Default for Config {
    fn default() -> Self {
        Config {
            search_url: None,
            search_api_key: None,
            search_results: DEFAULT_RESULTS,
            search_budget_chars: DEFAULT_BUDGET_CHARS,
            timeout: Duration::from_secs(DEFAULT_TIMEOUT_SECS),
        }
    }
}

impl Config {
    /// Neither search field set means web search is not registered at all — see
    /// `Registry::with_config`.
    pub fn from_env() -> Config {
        Config {
            search_url: env_string("SEARCH_URL"),
            search_api_key: env_string("SEARCH_API_KEY"),
            search_results: parse_env("SEARCH_RESULTS").unwrap_or(DEFAULT_RESULTS),
            search_budget_chars: parse_env("SEARCH_BUDGET_CHARS")
                .unwrap_or(DEFAULT_BUDGET_CHARS),
            timeout: parse_env("TOOL_TIMEOUT_SECS")
                .map(Duration::from_secs)
                .unwrap_or(Duration::from_secs(DEFAULT_TIMEOUT_SECS)),
        }
    }
}

fn env_string(key: &str) -> Option<String> {
    std::env::var(key).ok().map(|v| v.trim().to_string()).filter(|v| !v.is_empty())
}

fn parse_env<T: std::str::FromStr>(key: &str) -> Option<T> {
    std::env::var(key).ok()?.trim().parse().ok()
}
