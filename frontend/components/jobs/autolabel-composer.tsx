"use client"

import * as React from "react"
import { useRouter } from "next/navigation"
import { Play } from "lucide-react"

import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Panel } from "@/components/ui/panel"
import { toast } from "@/components/ui/toast"
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select"
import { useModels } from "@/hooks/use-models"
import { getSuite, type SuiteInfo } from "@/lib/benchmark"
import { queueAutolabel } from "@/lib/jobs"

const DEFAULT_CANDIDATES = 6
const DEFAULT_MAX_PROMPTS = 200
const DEFAULT_TEMPERATURE = 1.0

/**
 * Composing an auto-labelling run: pick a model, say how many candidates per
 * prompt, queue it.
 *
 * The model should normally be the one about to be preference-tuned — the labels
 * describe replies *it* produced, and data generated by a different model is
 * off-policy for the tune that consumes it.
 *
 * The run calibrates itself against the replies you rated by hand before it labels
 * anything, and refuses if it disagrees with them. So this form is only reachable
 * in a useful state once there are some hand ratings; the preference composer's
 * checklist is the guided way in.
 */
export function AutolabelComposer() {
  const router = useRouter()
  const { models, isLoading } = useModels()
  const [suite, setSuite] = React.useState<SuiteInfo | null>(null)
  const [chosenId, setChosenId] = React.useState("")
  const [candidates, setCandidates] = React.useState(DEFAULT_CANDIDATES)
  const [maxPrompts, setMaxPrompts] = React.useState(DEFAULT_MAX_PROMPTS)
  const [temperature, setTemperature] = React.useState(DEFAULT_TEMPERATURE)
  const [isSubmitting, setIsSubmitting] = React.useState(false)

  const modelId = chosenId || models[0]?.id || ""

  React.useEffect(() => {
    let alive = true
    getSuite()
      .then((info) => {
        if (alive) setSuite(info)
      })
      .catch(() => {})
    return () => {
      alive = false
    }
  }, [])

  const submit = async () => {
    setIsSubmitting(true)
    try {
      const job = await queueAutolabel({
        id_model: modelId,
        candidates,
        max_prompts: maxPrompts,
        temperature,
      })
      toast.success("Catalogue run queued.", job.label)
      router.push(`/jobs/${job.id_job}`)
    } catch (e) {
      toast.error(
        "Couldn't queue the run",
        e instanceof Error ? e.message : "Something went wrong."
      )
      setIsSubmitting(false)
    }
  }

  const valid = modelId && candidates >= 2 && maxPrompts >= 1 && temperature > 0

  return (
    <div className="space-y-6">
      <Panel title="Model" description="Which model writes the candidates">
        <div className="flex flex-wrap items-center gap-3">
          <Select
            value={modelId}
            onValueChange={(value) => setChosenId(value ?? "")}
            disabled={isSubmitting || isLoading}
          >
            <SelectTrigger className="w-full min-w-0 sm:w-80">
              <SelectValue>
                {(value: string | null) =>
                  models.find((model) => model.id === value)?.name ??
                  (isLoading ? "Loading models…" : "Select a model")
                }
              </SelectValue>
            </SelectTrigger>
            <SelectContent>
              {models.map((model) => (
                <SelectItem key={model.id} value={model.id}>
                  {model.name}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
      </Panel>

      <Panel
        title="Sampling"
        description="How many replies to compare, and how varied"
      >
        <dl className="space-y-3">
          <Field
            label="Candidates per prompt"
            hint="Every candidate gets its own verdict against the calibrated threshold, so this multiplies the catalogue directly — and the run gets proportionally longer."
          >
            <Input
              type="number"
              min={2}
              max={32}
              value={candidates}
              onChange={(e) => setCandidates(Number(e.target.value))}
              disabled={isSubmitting}
              className="h-8 w-24"
            />
          </Field>
          <Field
            label="Max prompts"
            hint="Taken from the distinct user messages already sent, newest first."
          >
            <Input
              type="number"
              min={1}
              value={maxPrompts}
              onChange={(e) => setMaxPrompts(Number(e.target.value))}
              disabled={isSubmitting}
              className="h-8 w-24"
            />
          </Field>
          <Field
            label="Temperature"
            hint="Above the chat default on purpose: candidates have to differ from each other or there is nothing to rank."
          >
            <Input
              type="number"
              min={0.1}
              step={0.1}
              value={temperature}
              onChange={(e) => setTemperature(Number(e.target.value))}
              disabled={isSubmitting}
              className="h-8 w-24"
            />
          </Field>
        </dl>

        <div className="mt-5 flex items-center gap-3">
          <Button
            onClick={submit}
            disabled={isSubmitting || !valid}
            className="gap-2"
          >
            <Play className="size-3.5" />
            {isSubmitting ? "Queueing…" : "Queue auto-labelling"}
          </Button>
        </div>
      </Panel>

      {/* Said before the run rather than after it: with no reference prose the
          judge has no English to score against, and the backend refuses rather
          than emitting near-random labels. Finding that out by spending a run is
          the wrong order. */}
      {suite && suite.corpus_files === 0 && (
        <p className="rounded-lg border border-dashed border-border px-4 py-3 text-sm text-muted-foreground">
          No reference corpus is installed in{" "}
          <code className="text-xs">{suite.corpus_dir}</code>. The judge scores
          replies against real English — the same corpus the benchmark uses — so
          this run will fail until one is added.
        </p>
      )}
    </div>
  )
}

function Field({
  label,
  hint,
  children,
}: {
  label: string
  hint: string
  children: React.ReactNode
}) {
  return (
    <div className="flex flex-wrap items-start justify-between gap-x-6 gap-y-1">
      <div className="min-w-0 flex-1">
        <dt className="text-sm">{label}</dt>
        <dd className="mt-0.5 text-xs text-muted-foreground">{hint}</dd>
      </div>
      {children}
    </div>
  )
}
