import { readdir, readFile, writeFile } from "node:fs/promises"
const directory = new URL(
  "../../contracts/modular-architecture/v1/schemas/",
  import.meta.url
)
const names = (await readdir(directory))
  .filter((name) => name.endsWith(".schema.json"))
  .sort()
/** Translates authoritative JSON schema declarations into structural TypeScript types. */
function typeOf(schema) {
  if (schema.$ref) return schema.$ref.split("/").at(-1)
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  if (schema.enum)
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ")
  if (schema.anyOf || schema.oneOf)
    return `(${(schema.anyOf ?? schema.oneOf).map(typeOf).join(" | ")})`
  if (schema.prefixItems)
    return `[${schema.prefixItems.map(typeOf).join(", ")}]`
  if (schema.type === "array") return `Array<${typeOf(schema.items)}>`
  if (schema.type === "object" || schema.properties) {
    if (!schema.properties)
      return `Record<string, ${schema.patternProperties ? typeOf(Object.values(schema.patternProperties)[0]) : typeof schema.additionalProperties === "object" ? typeOf(schema.additionalProperties) : "unknown"}>`
    return `{ ${Object.entries(schema.properties)
      .map(
        ([key, value]) =>
          `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${typeOf(value)}`
      )
      .join("; ")} }`
  }
  return (
    {
      integer: "number",
      number: "number",
      boolean: "boolean",
      string: "string",
      null: "null",
    }[schema.type] ?? "unknown"
  )
}
const schemas = new Map()
const runtimeSchemas = {}
for (const name of names) {
  const schema = JSON.parse(await readFile(new URL(name, directory), "utf8"))
  runtimeSchemas[name.replace(".schema.json", "")] = schema
  for (const [key, value] of Object.entries(schema.$defs ?? {}))
    schemas.set(key, value)
  schemas.set(name.replace(".schema.json", ""), schema)
}
const output = [
  "// Generated by scripts/generate-architecture-types.mjs from shared schemas; do not edit.",
  'import architectureSchemas from "./schemas.generated.json"',
  "export { architectureSchemas }",
  ...[...schemas]
    .sort()
    .map(([name, schema]) => `export type ${name} = ${typeOf(schema)}`),
  "export interface ArchitectureContracts {",
  ...names.map(
    (name) =>
      `  ${name.replace(".schema.json", "")}: ${name.replace(".schema.json", "")}`
  ),
  "}",
  "",
].join("\n")
const target = new URL(
  "../lib/architecture/contracts.generated.ts",
  import.meta.url
)
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error("Architecture types are stale; regenerate them")
} else await writeFile(target, output)

const runtimeTarget = new URL(
  "../lib/architecture/schemas.generated.json",
  import.meta.url
)
const runtimeOutput = JSON.stringify(runtimeSchemas) + "\n"
if (process.argv.includes("--check")) {
  if ((await readFile(runtimeTarget, "utf8")) !== runtimeOutput)
    throw new Error("Architecture runtime schemas are stale; regenerate them")
} else await writeFile(runtimeTarget, runtimeOutput)
